package com.minifocus.launcher.worker

import android.content.Context
import androidx.work.BackoffPolicy
import androidx.work.Constraints
import androidx.work.CoroutineWorker
import androidx.work.ExistingPeriodicWorkPolicy
import androidx.work.NetworkType
import androidx.work.PeriodicWorkRequestBuilder
import androidx.work.WorkManager
import androidx.work.WorkerParameters
import com.minifocus.launcher.LauncherApplication
import java.io.IOException
import java.util.concurrent.TimeUnit

/**
 * Checks for a signed remote patch every 12 hours. The network constraint means that if the
 * device is offline when the period elapses, the check runs as soon as it reconnects.
 */
class RemotePatchWorker(
    appContext: Context,
    params: WorkerParameters
) : CoroutineWorker(appContext, params) {

    override suspend fun doWork(): Result {
        val app = applicationContext as? LauncherApplication ?: return Result.failure()
        return try {
            app.container.remotePatchManager.checkForPatch()
            Result.success()
        } catch (_: IOException) {
            Result.retry()
        } catch (_: Exception) {
            // Malformed patch: nothing a retry will fix; try again next period.
            Result.success()
        }
    }

    companion object {
        private const val WORK_NAME = "remote-patch-check"

        fun schedule(context: Context) {
            val constraints = Constraints.Builder()
                .setRequiredNetworkType(NetworkType.CONNECTED)
                .build()
            val request = PeriodicWorkRequestBuilder<RemotePatchWorker>(12, TimeUnit.HOURS)
                .setConstraints(constraints)
                .setBackoffCriteria(BackoffPolicy.EXPONENTIAL, 30, TimeUnit.MINUTES)
                .build()
            WorkManager.getInstance(context).enqueueUniquePeriodicWork(
                WORK_NAME,
                ExistingPeriodicWorkPolicy.KEEP,
                request
            )
        }
    }
}
